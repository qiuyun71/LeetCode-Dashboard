def main():
    cats = []
    for cname, items in LC100:
        cats.append({
            "name": cname,
            "problems": [
                {"id": i, "name": n, "difficulty": d, "hint": h}
                for (i, n, d, h) in items
            ],
        })
    pool = [
        {"id": i, "name": n, "difficulty": d, "hint": h}
        for (i, n, d, h) in POOL
    ]

    total = sum(len(c["problems"]) for c in cats)
    plan = {
        "activeList": "lc100",
        "lists": {
            "lc100": {
                "name": "LeetCode 100",
                "startDate": "2026-10-06",
                "perDay": 4,
                "categories": cats,
                "pool": pool,
                "done": [],
                "board": [],
            }
        },
    }
    with open(PLAN, "w", encoding="utf-8") as f:
        json.dump(plan, f, ensure_ascii=False, indent=2)

    print("题单写入完成：%d 题 / %d 个分类 / 题池 %d 道"
          % (total, len(cats), len(pool)))


if __name__ == "__main__":
    main()
